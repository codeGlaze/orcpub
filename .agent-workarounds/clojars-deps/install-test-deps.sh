#!/usr/bin/env bash
# ---------------------------------------------------------------
# AGENT-ONLY -- safe to delete outside of agents/* branches.
#
# Installs Clojure test dependencies in Claude Code Web environments
# where repo.clojars.org is blocked by the egress proxy.
#
# What it does:
#   1. Ensures lein is installed (via apt if needed)
#   2. Creates profiles.clj to disable plugins/prep-tasks and
#      exclude dev/ from source-paths
#   3. Creates stub JARs for Clojars-only deps that aren't loaded
#      during JVM tests (satisfies Maven resolution only)
#   4. Downloads real source from GitHub for libraries that ARE
#      loaded during JVM test compilation
#   5. Adds Maven Central transitive deps to profiles.clj
#
# Usage:
#   bash .agent-workarounds/clojars-deps/install-test-deps.sh
#
# Prerequisites:
#   - Maven proxy should be running (see maven-proxy/)
#   - Java and jar command must be available
#   - curl and tar must be available
#
# Idempotent: safe to run multiple times.
# ---------------------------------------------------------------

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
M2_REPO="$HOME/.m2/repository"
TMP_DIR="/tmp/clojars-deps-$$"

# --- colors for output --------------------------------------------------------
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log()  { echo -e "${GREEN}[clojars-deps]${NC} $*"; }
warn() { echo -e "${YELLOW}[clojars-deps]${NC} $*"; }
err()  { echo -e "${RED}[clojars-deps]${NC} $*" >&2; }

# --- cleanup ------------------------------------------------------------------
cleanup() { rm -rf "$TMP_DIR"; }
trap cleanup EXIT
mkdir -p "$TMP_DIR"

# =============================================================================
# Step 1: Ensure lein is available
# =============================================================================
ensure_lein() {
  # Prefer apt-installed lein (has bundled standalone JAR)
  if command -v /usr/bin/lein &>/dev/null; then
    log "lein found at /usr/bin/lein"
    LEIN=/usr/bin/lein
    return
  fi

  # Check if any lein is available
  if command -v lein &>/dev/null; then
    # The pre-installed /usr/local/bin/lein may need self-install
    # which fails when GitHub releases are blocked
    if lein version &>/dev/null; then
      LEIN="$(command -v lein)"
      log "lein found at $LEIN"
      return
    fi
  fi

  # Install via apt
  log "Installing lein via apt..."
  if command -v apt-get &>/dev/null; then
    apt-get update -qq && apt-get install -y -qq leiningen 2>/dev/null
    LEIN=/usr/bin/lein
    log "lein installed via apt"
  else
    err "Cannot install lein: apt-get not available"
    err "Please install leiningen manually"
    exit 1
  fi
}

# =============================================================================
# Step 2: Create profiles.clj
# =============================================================================
create_profiles() {
  local profiles="$PROJECT_ROOT/profiles.clj"

  if [ -f "$profiles" ]; then
    log "profiles.clj already exists -- checking contents"
    if grep -q ':prep-tasks' "$profiles" && grep -q ':plugins' "$profiles"; then
      log "profiles.clj looks correct, skipping"
      return
    fi
    warn "profiles.clj exists but may be incomplete -- overwriting"
  fi

  cat > "$profiles" << 'CLJ'
;; Auto-generated by .agent-workarounds/clojars-deps/install-test-deps.sh
;; This file is in .gitignore and will not be committed.
;;
;; Purpose: Allow `lein test` to run in Claude Code Web environments
;; where Clojars (repo.clojars.org) is blocked by the egress proxy.
{:user {:plugins ^:replace []
        :prep-tasks ^:replace ["javac" "compile"]
        :dependencies [[org.clojure/tools.logging "1.1.0"]
                       [net.cgrand/macrovich "0.2.1"]]}
 :dev {:source-paths ^:replace ["src/clj" "src/cljc" "src/cljs" "web/cljs"]}}
CLJ
  log "Created profiles.clj"
}

# =============================================================================
# Step 3: Create stub JARs for Clojars-only deps
# =============================================================================
create_stub() {
  local group="$1" artifact="$2" version="$3"
  local gpath="${group//\./\/}"
  local dir="$M2_REPO/$gpath/$artifact/$version"
  local jar="$dir/$artifact-$version.jar"
  local pom="$dir/$artifact-$version.pom"

  if [ -f "$jar" ] && [ -s "$jar" ]; then
    return  # already exists and non-empty
  fi

  mkdir -p "$dir"

  # Create minimal POM
  cat > "$pom" << EOF
<?xml version="1.0" encoding="UTF-8"?>
<project>
  <modelVersion>4.0.0</modelVersion>
  <groupId>$group</groupId>
  <artifactId>$artifact</artifactId>
  <version>$version</version>
</project>
EOF

  # Create empty JAR (just a manifest)
  local stub_dir="$TMP_DIR/stub-jar"
  mkdir -p "$stub_dir"
  echo "Manifest-Version: 1.0" > "$stub_dir/MANIFEST.MF"
  (cd "$stub_dir" && jar cfm "$jar" MANIFEST.MF)
}

