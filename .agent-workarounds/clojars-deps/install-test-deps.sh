# =============================================================================
# Step 4: Download and install real source JARs from GitHub
# =============================================================================

# Download a GitHub repo tarball with retry logic
download_github_tarball() {
  local owner="$1" repo="$2" ref="$3" output="$4"
  local url="https://api.github.com/repos/$owner/$repo/tarball/$ref"
  local attempt=0
  local max_attempts=4
  local delay=2

  while [ $attempt -lt $max_attempts ]; do
    attempt=$((attempt + 1))
    local status
    status=$(curl -sL -o "$output" -w "%{http_code}" \
      -H "Accept: application/vnd.github+json" "$url" 2>/dev/null)

    if [ "$status" = "200" ] && [ -s "$output" ]; then
      return 0
    fi

    if [ $attempt -lt $max_attempts ]; then
      warn "Download attempt $attempt failed (HTTP $status), retrying in ${delay}s..."
      sleep $delay
      delay=$((delay * 2))
    fi
  done

  err "Failed to download $owner/$repo@$ref after $max_attempts attempts"
  return 1
}

# Build a JAR from extracted source and install to Maven repo
install_source_jar() {
  local group="$1" artifact="$2" version="$3" src_subdir="$4" extract_dir="$5"
  local gpath="${group//\./\/}"
  local dest_dir="$M2_REPO/$gpath/$artifact/$version"
  local dest_jar="$dest_dir/$artifact-$version.jar"
  local dest_pom="$dest_dir/$artifact-$version.pom"

  mkdir -p "$dest_dir"

  # Find the extracted directory (GitHub tarballs have owner-repo-hash/ prefix)
  local src_root
  src_root=$(find "$extract_dir" -maxdepth 1 -type d -name '*' | tail -1)

  if [ ! -d "$src_root/$src_subdir" ]; then
    err "Source directory $src_subdir not found in extracted tarball"
    return 1
  fi

  # Build JAR from source
  (cd "$src_root/$src_subdir" && jar cf "$dest_jar" .)

  # Create POM
  cat > "$dest_pom" << EOF
<?xml version="1.0" encoding="UTF-8"?>
<project>
  <modelVersion>4.0.0</modelVersion>
  <groupId>$group</groupId>
  <artifactId>$artifact</artifactId>
  <version>$version</version>
</project>
EOF

  local count
  count=$(jar tf "$dest_jar" | grep -cE '\.(clj|cljc|cljs)$' || true)
  log "Installed $group:$artifact:$version ($count source files)"
}

install_real_deps() {
  log "Downloading real source for libraries needed at compile time..."

  # --- re-frame 0.10.9 ---
  # Required by: template.cljc, options.cljc (unconditional require)
  local rf_jar="$M2_REPO/re-frame/re-frame/0.10.9/re-frame-0.10.9.jar"
  if [ -f "$rf_jar" ] && jar tf "$rf_jar" 2>/dev/null | grep -q 'core.cljc'; then
    log "re-frame already has real source, skipping"
  else
    local rf_dir="$TMP_DIR/re-frame"
    mkdir -p "$rf_dir"
    download_github_tarball "day8" "re-frame" "v0.10.9" "$rf_dir/re-frame.tar.gz"
    (cd "$rf_dir" && tar xzf re-frame.tar.gz)
    install_source_jar "re-frame" "re-frame" "0.10.9" "src" "$rf_dir"
  fi

  # --- reagent 0.7.0 ---
  # Required by: components.cljc (unconditional require)
  local rg_jar="$M2_REPO/reagent/reagent/0.7.0/reagent-0.7.0.jar"
  if [ -f "$rg_jar" ] && jar tf "$rg_jar" 2>/dev/null | grep -q 'core.clj'; then
    log "reagent already has real source, skipping"
  else
    local rg_dir="$TMP_DIR/reagent"
    mkdir -p "$rg_dir"
    download_github_tarball "reagent-project" "reagent" "v0.7.0" "$rg_dir/reagent.tar.gz"
    (cd "$rg_dir" && tar xzf reagent.tar.gz)
    install_source_jar "reagent" "reagent" "0.7.0" "src" "$rg_dir"
  fi

  # --- macrovich 0.2.1 ---
  # Transitive dep of reagent; required at macro-expansion time
  local mv_jar="$M2_REPO/net/cgrand/macrovich/0.2.1/macrovich-0.2.1.jar"
  if [ -f "$mv_jar" ] && jar tf "$mv_jar" 2>/dev/null | grep -q 'macrovich.cljc'; then
    log "macrovich already has real source, skipping"
  else
    local mv_dir="$TMP_DIR/macrovich"
    mkdir -p "$mv_dir"
    # macrovich has no version tags; use master
    download_github_tarball "cgrand" "macrovich" "master" "$mv_dir/macrovich.tar.gz"
    (cd "$mv_dir" && tar xzf macrovich.tar.gz)
    install_source_jar "net.cgrand" "macrovich" "0.2.1" "src" "$mv_dir"
  fi
}

# =============================================================================
# Step 5: Verify
# =============================================================================
verify() {
  log "Verifying setup..."

  # Check that lein can resolve deps
  if (cd "$PROJECT_ROOT" && $LEIN classpath &>/dev/null); then
    log "lein classpath resolves successfully"
  else
    warn "lein classpath failed -- some deps may still be missing"
    warn "Run: cd $PROJECT_ROOT && $LEIN test :only orcpub.dnd.e5.ac-test"
    warn "and check error output for missing namespaces"
    return 1
  fi

  log "Setup complete. Run tests with:"
  log "  $LEIN test                                    # all tests"
  log "  $LEIN test :only orcpub.dnd.e5.ac-test        # AC tests only"
}

# =============================================================================
# Main
# =============================================================================
main() {
  log "Setting up Clojure test dependencies for Claude Code Web..."
  log "Project root: $PROJECT_ROOT"
  log ""

  ensure_lein
  create_profiles
  create_all_stubs
  install_real_deps
  verify

  log ""
  log "Done. Dependencies installed for offline test execution."
}

main "$@"
